"""TEN class: evidence records and their IMMUTABLE revisions (D-P0-007 s5, decision C-6). Composite same-tenant FK, immutability and state-machine
triggers, and the full-text column are created in SQL (migration 0002). The searchable `search_vector` column is generated by the database and
deliberately not mapped here: it is read only by the reviewed search query."""
from __future__ import annotations

from django.db import models

from ngrc.core.models import TenantOwnedModel


class Evidence(TenantOwnedModel):
    class DataClass(models.TextChoices):
        CONFIDENTIAL = "C"
        RESTRICTED = "R"

    title = models.CharField(max_length=200)
    description = models.TextField(blank=True, max_length=2000)
    data_class = models.CharField(max_length=1, choices=DataClass.choices, default=DataClass.CONFIDENTIAL)
    created_by = models.UUIDField(null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ten_evidence"
        constraints = [
            models.UniqueConstraint(fields=["tenant", "id"], name="ten_evidence_tenant_id_uniq"),  # target of the composite FK
            models.CheckConstraint(condition=models.Q(data_class__in=["C", "R"]), name="ten_evidence_class"),
        ]


class EvidenceRevision(TenantOwnedModel):
    """One uploaded file version. Content columns are immutable; only the scan outcome may be recorded, once."""

    class State(models.TextChoices):
        SCAN_PENDING = "scan_pending"   # stored, not yet cleared: NEVER downloadable
        COLLECTED = "collected"         # clean scan: downloadable
        QUARANTINED = "quarantined"     # detected malware: retained for investigation, NEVER served

    evidence_id = models.UUIDField()    # composite FK (tenant_id, evidence_id) -> ten_evidence(tenant_id, id) created in SQL
    revision_no = models.IntegerField()
    filename = models.CharField(max_length=255)          # original name: METADATA ONLY, never used as a path
    declared_type = models.CharField(max_length=100)
    detected_type = models.CharField(max_length=100)
    size_bytes = models.BigIntegerField()
    sha256 = models.CharField(max_length=64)
    storage_key = models.CharField(max_length=200)       # server-generated from UUIDs only
    state = models.CharField(max_length=16, choices=State.choices, default=State.SCAN_PENDING)
    scan_detail = models.CharField(max_length=100, blank=True)
    scanned_at = models.DateTimeField(null=True)
    created_by = models.UUIDField(null=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "ten_evidence_revision"
        constraints = [
            # target of ngrc.controls.EvidenceLink's composite FK (D-P3-002) - same reasoning as ten_evidence's own tenant_id_uniq above.
            models.UniqueConstraint(fields=["tenant", "id"], name="ten_evidence_revision_tenant_id_uniq"),
            models.UniqueConstraint(fields=["tenant", "evidence_id", "revision_no"], name="ten_evidence_revision_no_uniq"),
            models.UniqueConstraint(fields=["tenant", "storage_key"], name="ten_evidence_revision_key_uniq"),
            models.CheckConstraint(condition=models.Q(state__in=["scan_pending", "collected", "quarantined"]), name="ten_evidence_revision_state"),
            models.CheckConstraint(condition=models.Q(size_bytes__gte=0), name="ten_evidence_revision_size"),
        ]
